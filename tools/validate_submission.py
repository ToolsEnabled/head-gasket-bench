#!/usr/bin/env python3
"""Validate one submitted run folder, runs/submitted/<name>/.

    python3 tools/validate_submission.py runs/submitted/<name>
    python3 tools/validate_submission.py --write-result runs/submitted/<name>

A submission holds exactly five files: run.json, actions.jsonl and report.json as
the environment wrote them, RESULT.md (generated by --write-result), and
SUBMISSION.json (model_label, client, variant, date, submitter, optional notes).

Checks, in order; the first failure ends the run:

  files      exactly the five files, regular files, within the size limits
  declaration SUBMISSION.json well formed (plain text values, a real YYYY-MM-DD
             date); variant matches the record
  secrets    no key-shaped strings and no personal or machine-local paths, in the
             raw files and in the decoded JSON strings
  chain      canonical record, every digest, the action hash chain, the state
             links, 1 to 1,024 attempts, actions.jsonl exactly the journal, and
             report.json exactly the envelope the environment writes for this
             record (only its wall-clock seconds are free)
  duplicate  the tool calls are not those of a published scripted record, of a
             withheld ToolsEnabled record or of another submission; a near copy
             (most calls, in order, those of one of them) passes with a request
             for a maintainer's review
  pins       configuration is one of env/'s pinned V1-V5 configurations and the
             runtime is env/'s current source manifest; same CPython version
  replay     the shipped env/bin/headgasket-mcp launcher reproduces run.json exactly
  scorer     scorer/hgj_scorer.py score accepts the record and agrees with the
             environment's embedded score on every primary checkpoint and on every
             shared field both scorers determine; RESULT.md is exactly the file
             --write-result generates

Prints one line (PASS or FAIL with the check name) and exits 0 only on PASS. A PASS
line that ends with "REVIEW BY HAND" marks a near copy for the maintainer.
Standard library only; nothing here reads the network.
"""
import argparse
import datetime
import hashlib
import json
import math
import re
import subprocess
import sys
import tempfile
import unicodedata
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
ENV = REPO / 'env'
SCORER = REPO / 'scorer'
MB = 1024 * 1024
MAX_SUBMISSION_BYTES = 64 * MB
LIMITS = {'run.json': 64 * MB, 'actions.jsonl': 64 * MB, 'report.json': 64 * MB,
          'RESULT.md': 64 * 1024, 'SUBMISSION.json': 16 * 1024}
DECLARATION_KEYS = {'model_label', 'client', 'variant', 'date', 'submitter'}
OPTIONAL_KEYS = {'notes'}
VARIANTS = ('V1', 'V2', 'V3', 'V4', 'V5')
# Used with fullmatch: '$' would also accept a trailing newline, and \d any Unicode digit.
NAME_RE = re.compile(r'[a-z0-9][a-z0-9._-]{2,99}')
DATE_RE = re.compile(r'[0-9]{4}-[0-9]{2}-[0-9]{2}')
# Declaration values are shown in RESULT.md and on the board, so they must be plain,
# visible text: no character of these Unicode categories (control; format, which holds
# every bidirectional mark, override and isolate including U+061C, and the zero-width
# and byte-order marks; surrogate; private use; unassigned; line and paragraph
# separator), and no backticks (they would end RESULT.md's code spans). notes is shown
# nowhere and may also hold tabs and line breaks.
HIDDEN_CATEGORIES = frozenset({'Cc', 'Cf', 'Cs', 'Co', 'Cn', 'Zl', 'Zp'})
NOTES_ALLOWED = frozenset('\t\n\r')
TOP_KEYS = {'actions', 'budget', 'config', 'config_sha256', 'environment_source', 'environment_source_sha256',
            'final_state', 'final_state_sha256', 'finished', 'initial_state', 'initial_state_sha256', 'schema',
            'score', 'score_sha256', 'scoring_status'}
ACTION_KEYS = {'human_time_charge', 'input', 'name', 'post_state_sha256', 'pre_state_sha256',
               'previous_action_sha256', 'result', 'seq'}
MAX_ACTIONS = 1024
# A record that shares at least this share of the shorter record's calls, in order, with
# a scripted record or another submission (and at least NEAR_COPY_MIN_CALLS calls) is
# marked for a maintainer's review.
NEAR_COPY_SHARE = 0.8
NEAR_COPY_MIN_CALLS = 20
SCORER_REVISION = 'amendment-2-20261010'
# The independent scorer labels a finished run that has no final timing check of
# enough revolutions 'missing_timing_verification'; the environment has no such
# mistake type (it scores the same fact in checkpoint CP11, which both scorers
# decide and which must agree). The mistake-type comparison therefore leaves this
# independent-only label out.
INDEPENDENT_ONLY_MISTAKE_TYPES = frozenset({'missing_timing_verification'})
# What env/hgj/repair_report.py (pinned) writes into report.json.
REPORT_TIME_SOURCE = 'MCP server session monotonic clock'
REPORT_TOKEN_SOURCE = 'Not supplied by a provider usage receipt'
ENDED_REASONS = ('input_ended_without_finish', 'interrupted', 'transport_error')

# Key-shaped strings. Built to match real credential formats, not ordinary words. Some
# patterns are split into concatenated pieces so that this file itself contains no
# path or token prefix that a repository scan would flag.
SECRET_PATTERNS = [
    ('private key block', rb'-----BEGIN [A-Z ]{0,40}PRIVATE KEY-----'),
    ('provider API key', rb'(?<![A-Za-z0-9])sk-(?:ant-|proj-|live-|test-|or-)?[A-Za-z0-9_\-]{20,}'),
    ('GitHub token', rb'(?<![A-Za-z0-9])(?:ghp|gho|ghu|ghs|ghr)_[A-Za-z0-9]{30,}'),
    ('GitHub token', rb'github' + rb'_pat_[A-Za-z0-9_]{30,}'),
    ('cloud access key', rb'(?<![A-Z0-9])(?:AKIA|ASIA)[0-9A-Z]{16}(?![A-Z0-9])'),
    ('chat token', rb'(?<![A-Za-z0-9])xox[abprs]-[A-Za-z0-9\-]{10,}'),
    ('cloud API key', rb'(?<![A-Za-z0-9])AIza[0-9A-Za-z_\-]{35}'),
    ('model hub token', rb'(?<![A-Za-z0-9])hf_[A-Za-z0-9]{30,}'),
    ('GitLab token', rb'glpat-[A-Za-z0-9_\-]{20,}'),
    ('bearer credential', rb'(?i)\bbearer\s+[A-Za-z0-9._~+/\-]{24,}'),
    ('assigned credential', rb'(?i)\b(?:api[_-]?key|secret|access[_-]?token|auth[_-]?token|password|token|accountkey)'
                            rb'["\']?\s*[:=]\s*["\']?[^"\'\s,;}]{12,}'),
    ('JSON web token', rb'(?<![A-Za-z0-9_-])eyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\.'),
    ('provider API key', rb'(?<![A-Za-z0-9])(?:xai|pplx)-[A-Za-z0-9]{20,}'),
    ('provider API key', rb'(?<![A-Za-z0-9])(?:gsk|npm|r8)_[A-Za-z0-9]{20,}'),
    ('payment API key', rb'(?<![A-Za-z0-9])[sr]k_(?:live|test)_[A-Za-z0-9]{20,}'),
]
PATH_PATTERNS = [
    # Any user-name characters (also non-ASCII) and either separator.
    ('home directory path', rb'[\\/]' + rb'home[\\/][^\\/\s"\'<>]+'),
    ('home directory path', rb'/Users/[^\\/\s"\'<>]+'),
    ('home directory path', rb'(?i)(?<![A-Za-z0-9._~%-])/users/[^\\/\s"\'<>]+'),
    ('home directory path', rb'(?i)[A-Z]:(?:\\\\|\\|/)+Users(?:\\\\|\\|/)+'),
    ('home directory path', rb'(?i)\\\\wsl(?:\.localhost|\$)'),
    ('machine-local path', rb'/(?:root|mnt|sandbox|private/var|var/folders|media|run/user)/'),
    ('home directory path', rb'(?<![A-Za-z0-9._~%-])/u/[A-Za-z0-9._-]+'),
    ('home directory path', rb'(?<![A-Za-z0-9])~/[A-Za-z0-9._\-]+'),
]
COMPILED = [(label, re.compile(pattern)) for label, pattern in SECRET_PATTERNS + PATH_PATTERNS]


class Fail(Exception):
    def __init__(self, check, message):
        super().__init__(message)
        self.check = check


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def canonical(value):
    return (json.dumps(value, sort_keys=True, separators=(',', ':'), ensure_ascii=False,
                       allow_nan=False) + '\n').encode('utf-8')


def digest(value):
    return sha(canonical(value))


def require(condition, check, message):
    if not condition:
        raise Fail(check, message)


# ---------------------------------------------------------------- the checks

def check_files(folder):
    require(folder.is_dir() and not folder.is_symlink(), 'files', f'{folder} is not a folder')
    require(NAME_RE.fullmatch(folder.name) is not None, 'files',
            'folder name must be 3-100 characters: lower case letters, digits, ".", "_" or "-", '
            'starting with a letter or digit')
    entries = sorted(p.name for p in folder.iterdir())
    require(entries == sorted(LIMITS), 'files',
            'the folder must hold exactly ' + ', '.join(sorted(LIMITS)) + '; found ' + (', '.join(entries) or 'nothing'))
    total = 0
    for name, limit in LIMITS.items():
        path = folder / name
        require(path.is_file() and not path.is_symlink(), 'files', f'{name} is not a regular file')
        size = path.stat().st_size
        require(size <= limit, 'files', f'{name} is {size} bytes; the limit is {limit}')
        total += size
    require(total <= MAX_SUBMISSION_BYTES, 'files',
            f'submission is {total} bytes; the limit is {MAX_SUBMISSION_BYTES}. Each look call adds about 0.4 MB '
            '(its result of about 200,000 characters is stored in run.json and again in actions.jsonl), '
            'so a run with about 150 or more look calls is too large to submit')
    return {name: (folder / name).read_bytes() for name in LIMITS}


def check_declaration(raw):
    try:
        declaration = json.loads(raw)
    except (ValueError, UnicodeDecodeError) as error:
        raise Fail('declaration', f'SUBMISSION.json is not JSON: {error}')
    require(isinstance(declaration, dict), 'declaration', 'SUBMISSION.json must be an object')
    keys = set(declaration)
    require(DECLARATION_KEYS <= keys, 'declaration', 'SUBMISSION.json needs ' + ', '.join(sorted(DECLARATION_KEYS - keys)))
    require(keys <= DECLARATION_KEYS | OPTIONAL_KEYS, 'declaration',
            'SUBMISSION.json has unknown keys: ' + ', '.join(sorted(keys - DECLARATION_KEYS - OPTIONAL_KEYS)))
    for key in sorted(keys):
        value = declaration[key]
        require(isinstance(value, str) and value.strip() and len(value) <= (2000 if key == 'notes' else 200),
                'declaration', f'SUBMISSION.json {key} must be a non-empty string (at most 200 characters, notes 2000)')
        forbidden = hidden_character(value, shown=key != 'notes')
        if forbidden is not None:
            raise Fail('declaration', f'SUBMISSION.json {key} contains U+{ord(forbidden):04X}; use plain text (no control, '
                       'bidirectional, zero-width or other invisible characters'
                       + ('' if key == 'notes' else ', no line breaks and no backticks') + ')')
    require(declaration['variant'] in VARIANTS, 'declaration', 'variant must be one of ' + ', '.join(VARIANTS))
    require(DATE_RE.fullmatch(declaration['date']) is not None and real_date(declaration['date']), 'declaration',
            'date must be a real date written YYYY-MM-DD')
    return declaration


def hidden_character(value, shown):
    """The first character a declaration value may not hold, or None."""
    for char in value:
        if shown and char == '`':
            return char
        if not shown and char in NOTES_ALLOWED:
            continue
        if unicodedata.category(char) in HIDDEN_CATEGORIES:
            return char
    return None


def real_date(text):
    try:
        datetime.date.fromisoformat(text)
    except ValueError:
        return False
    return True


def check_secrets(files):
    views = dict(files)
    # JSON escapes (for example \u002f for "/") would hide a value from a scan of the
    # raw bytes; scan the decoded strings too.
    for name in ('SUBMISSION.json', 'report.json'):
        try:
            views[name + ' (decoded)'] = canonical(json.loads(files[name]))
        except (ValueError, UnicodeDecodeError, RecursionError):
            pass  # the declaration and chain checks report it
    for name, raw in views.items():
        for label, pattern in COMPILED:
            found = pattern.search(raw)
            if found:
                line = raw.count(b'\n', 0, found.start()) + 1
                raise Fail('secrets', f'{name} line {line}: {label} ({found.group(0)[:12].decode("utf-8", "replace")}...)')


def check_chain(files):
    raw = files['run.json']
    try:
        record = json.loads(raw)
    except (ValueError, UnicodeDecodeError) as error:
        raise Fail('chain', f'run.json is not JSON: {error}')
    require(isinstance(record, dict) and record.get('schema') == 'hgj/run/v2', 'chain', 'run.json is not an hgj/run/v2 record')
    require(set(record) == TOP_KEYS, 'chain', 'run.json top-level keys differ from the record schema: '
            + ', '.join(sorted(set(record) ^ TOP_KEYS)))
    require(canonical(record) == raw, 'chain', 'run.json is not in canonical encoding (it was edited or re-encoded)')
    for key in ('config', 'environment_source', 'initial_state', 'final_state', 'score'):
        require(digest(record[key]) == record[key + '_sha256'], 'chain', f'{key}_sha256 does not match {key}')
    actions = record['actions']
    check_attempt_count(actions)
    previous, state = record['config_sha256'], record['initial_state_sha256']
    for index, row in enumerate(actions, 1):
        require(isinstance(row, dict) and set(row) == ACTION_KEYS, 'chain', f'action {index}: unexpected fields')
        require(row['seq'] == index, 'chain', f'action {index}: seq is {row["seq"]}')
        require(row['previous_action_sha256'] == previous, 'chain', f'action {index}: previous_action_sha256 breaks the hash chain')
        require(row['pre_state_sha256'] == state, 'chain', f'action {index}: pre_state_sha256 does not follow the previous state')
        previous, state = digest(row), row['post_state_sha256']
    require(state == record['final_state_sha256'], 'chain', 'the last action does not end in final_state_sha256')
    budget = record['budget']
    require(isinstance(budget, dict) and budget.get('limit') == MAX_ACTIONS and budget.get('used') == len(actions),
            'chain', 'budget does not describe the journal')
    require(files['actions.jsonl'] == b''.join(canonical(row) for row in actions), 'chain',
            'actions.jsonl differs from the record journal')
    try:
        report = json.loads(files['report.json'])
    except (ValueError, UnicodeDecodeError) as error:
        raise Fail('chain', f'report.json is not JSON: {error}')
    require(isinstance(report, dict) and report.get('schema') == 'hgj/repair-run-report/v1', 'chain',
            'report.json is not an hgj/repair-run-report/v1 envelope')
    require(report.get('run_sha256') == sha(raw), 'chain', 'report.json run_sha256 is not the SHA-256 of run.json')
    require(report.get('score_sha256') == record['score_sha256'], 'chain', 'report.json score_sha256 differs from the record')
    require(report.get('finished') == record['finished'], 'chain', 'report.json finished differs from the record')
    require((report.get('tool_calls') or {}).get('attempted') == len(actions), 'chain',
            'report.json tool_calls.attempted differs from the journal')
    check_report(report, record, files['report.json'])
    return record


def check_attempt_count(actions):
    require(isinstance(actions, list), 'chain', 'the record has no action journal')
    require(len(actions) > 0, 'chain', 'the record holds no tool calls, so there is nothing to score '
            '(a client that only connected to the server made no run)')
    require(len(actions) <= MAX_ACTIONS, 'chain',
            f'the record holds {len(actions)} tool-call attempts, more than the {MAX_ACTIONS:,}-attempt budget. '
            'The pinned environment records a call made after turns_remaining reached 0 (the launcher of release 0.1.2 '
            f'and later answers such a call without recording it), and the pinned independent scorer accepts at most '
            f'{MAX_ACTIONS:,} attempts, so this run cannot be scored or submitted (a known issue of this environment '
            'epoch; see SUBMISSIONS.md)')


def report_reasons(record):
    """The (status, terminal_reason) pairs env/hgj/mcp.py can write for this record.

    The server rewrites report.json after every call with terminal reason 'running'
    (status in_progress), and once more when it stops; a client that kills the
    server leaves the per-call version."""
    if record['finished']:
        return {('finished', 'finished')}
    budget = record.get('budget') or {}
    if budget.get('exhausted'):
        return {('incomplete', 'budget_exhausted')}
    factors = (record.get('config') or {}).get('factors') or {}
    if len(record['actions']) >= factors.get('tool_call_limit', MAX_ACTIONS):
        return {('incomplete', 'tool_call_limit')}
    return {('in_progress', None)} | {('incomplete', reason) for reason in ENDED_REASONS}


def expected_report(record, seconds, status, reason):
    """report.json as env/hgj/repair_report.py report_for_run writes it (no token receipt)."""
    score = record['score']
    actions = record['actions']
    successful = sum(1 for row in actions if row['result'].get('ok') is True)
    return {'schema': 'hgj/repair-run-report/v1', 'run_sha256': digest(record), 'score_sha256': digest(score),
            'finished': record['finished'], 'status': status, 'terminal_reason': reason,
            'real_time': {'seconds': seconds, 'source': REPORT_TIME_SOURCE},
            'tokens': {'input': None, 'output': None, 'total': None, 'status': 'not_recorded',
                       'source': REPORT_TOKEN_SOURCE},
            'tool_calls': {'attempted': len(actions), 'successful': successful, 'refused': len(actions) - successful},
            'human_time': score['human_time'], 'mistakes': score['mistakes'],
            'bolt_accuracy': score['bolt_accuracy'], 'checklist_accuracy': score['checklist_accuracy'],
            'coverage': score['coverage'], 'reference_sha256': score['reference_sha256'],
            'primary_score': score.get('primary_score')}


def check_report(report, record, raw):
    """Every field of report.json follows from the record except the session's wall-clock seconds."""
    seconds = (report.get('real_time') or {}).get('seconds')
    require(type(seconds) in (int, float) and math.isfinite(seconds) and seconds >= 0, 'chain',
            'report.json real_time.seconds must be a finite, non-negative number')
    pair = (report.get('status'), report.get('terminal_reason'))
    require(pair in report_reasons(record), 'chain',
            f'report.json status and terminal_reason {pair} do not fit the record')
    try:
        expected = expected_report(record, seconds, *pair)
    except (KeyError, TypeError, AttributeError):
        raise Fail('chain', 'run.json score lacks a field report.json copies')
    require(canonical(expected) == raw, 'chain',
            'report.json differs from the report the environment writes for this record '
            '(only real_time.seconds may differ; do not edit it)')


# ---------------------------------------------------------------- duplicates

def call_keys(actions):
    """The tool calls a record made, in order, one digest per call (name and input only)."""
    return [digest([row.get('name'), row.get('input')]) if isinstance(row, dict) else None for row in actions]


def journal_calls(path):
    """The calls of a saved actions.jsonl, or None when it cannot be read."""
    try:
        if path.is_symlink() or not path.is_file() or path.stat().st_size > LIMITS['actions.jsonl']:
            return None
        return [json.loads(line) for line in path.read_bytes().splitlines() if line.strip()]
    except (OSError, ValueError, UnicodeDecodeError, RecursionError):
        return None


def shared_calls(mine, theirs):
    """How many calls two records have in common in the same order: the length of the
    longest common subsequence of the two call lists (bit-parallel, Crochemore et al.
    2001; one big-integer step per call, so a 1,024-call pair takes milliseconds)."""
    masks = {}
    for index, call in enumerate(theirs):
        masks[call] = masks.get(call, 0) | (1 << index)
    full = (1 << len(theirs)) - 1
    row = full
    for call in mine:
        match = row & masks.get(call, 0)
        row = ((row + match) | (row - match)) & full
    return len(theirs) - bin(row).count('1')


def scripted_records():
    """(label, actions.jsonl) of the published scripted records, runs/family and runs/reference."""
    known = []
    for kind in ('family', 'reference'):
        base = REPO / 'runs' / kind
        if base.is_dir():
            known += [(f'runs/{kind}/{case.name}', case / 'actions.jsonl')
                      for case in sorted(base.iterdir()) if case.is_dir() and not case.is_symlink()]
    return known


def other_submissions(folder):
    """(label, actions.jsonl) of the other submissions, on main and beside this folder."""
    roots, known = [], []
    for root in (REPO / 'runs' / 'submitted', Path(folder).parent):
        if root.is_dir() and root.resolve() not in [r.resolve() for r in roots]:
            roots.append(root)
    here = Path(folder).resolve()
    for root in roots:
        for other in sorted(root.iterdir()):
            if other.name == Path(folder).name or other.is_symlink() or not other.is_dir() or other.resolve() == here:
                continue
            known.append((f'runs/submitted/{other.name}', other / 'actions.jsonl'))
    return known


def closest(mine, known):
    """The known record with the most calls in common with mine, in order:
    (label, shared calls, its number of calls), or None."""
    best = None
    for label, path in known:
        calls = journal_calls(path)
        if not calls or not all(isinstance(row, dict) for row in calls):
            continue
        theirs = call_keys(calls)
        shared = shared_calls(mine, theirs)
        if best is None or shared > best[1]:
            best = (label, shared, len(theirs))
    return best


def near_copy(mine, match):
    """True when most calls of one record are, in order, the calls of the other: at
    least NEAR_COPY_SHARE of the shorter record and at least NEAR_COPY_MIN_CALLS calls.
    The model runs ToolsEnabled made share at most 52% with any scripted record; a
    scripted record with a call added, dropped or changed shares nearly 100%."""
    if match is None:
        return False
    _label, shared, theirs = match
    return shared >= NEAR_COPY_MIN_CALLS and shared >= NEAR_COPY_SHARE * min(len(mine), theirs)


def describe_match(mine, match):
    if match is None:
        return 'none'
    label, shared, theirs = match
    return f'{shared} of {len(mine)}, in order ({label}, {theirs} calls)'


def check_duplicate(folder, record, files):
    """Refuse a copy (the same tool calls as a published scripted record or another
    submission, or the bytes of a withheld ToolsEnabled record) and find near copies.

    Returns (closest scripted record, review note or None). A record whose calls are
    mostly, in order, those of a scripted record or another submission is not refused
    (a model can repeat much of a correct procedure, and ToolsEnabled cannot tell a
    model run from an edited scripted run), but the PASS line asks for a maintainer's
    review, and RESULT.md states how many calls the run shares with the closest
    scripted record."""
    mine = call_keys(record['actions'])
    scripted, submitted = scripted_records(), other_submissions(folder)
    for label, path in scripted + submitted:
        calls = journal_calls(path)
        if calls is not None and all(isinstance(row, dict) for row in calls) and call_keys(calls) == mine:
            kind = 'the submission' if label.startswith('runs/submitted/') else 'the published record'
            raise Fail('duplicate', f'the record makes the same tool calls as {kind} {label}; a submission must be a new run')
    hashes = {sha(files['run.json']), sha(files['actions.jsonl'])}
    exploratory = REPO / 'runs' / 'exploratory'
    for provenance in sorted(exploratory.glob('*/provenance.json')) if exploratory.is_dir() else []:
        try:
            listed = (json.loads(provenance.read_bytes()).get('withheld_files') or {}).values()
        except (OSError, ValueError, AttributeError):
            continue
        # Either "file": "<sha256>" or "file": {"bytes": ..., "sha256": "<sha256>"}.
        withheld = {item.get('sha256') if isinstance(item, dict) else item for item in listed}
        require(not hashes & withheld, 'duplicate',
                f'the record is the withheld record of runs/exploratory/{provenance.parent.name}')
    nearest = closest(mine, scripted)
    review = None
    for match in (nearest, closest(mine, submitted)):
        if near_copy(mine, match):
            review = (f'REVIEW BY HAND: {match[1]} of its {len(mine)} calls are, in order, calls of {match[0]} '
                      f'({match[2]} calls), so it may be an edited copy; check that a model made it')
            break
    return nearest, review


def check_pins(record, declaration):
    pins = json.loads((ENV / 'configs' / 'PINS.json').read_bytes())
    known = {item['sha256']: name for name, item in pins['configurations'].items()}
    variant = known.get(record['config_sha256'])
    require(variant is not None, 'pins', f'configuration {record["config_sha256"]} is not one of env/configs/PINS.json')
    require(record['config'].get('variant_id') == variant == declaration['variant'], 'pins',
            f'variant: configuration {variant}, record {record["config"].get("variant_id")}, SUBMISSION.json {declaration["variant"]}')
    source = record['environment_source']
    require(source.get('source_manifest_sha256') == pins['source_manifest_sha256'], 'pins',
            'the record was not made with the current environment runtime (source manifest '
            f'{source.get("source_manifest_sha256")}, expected {pins["source_manifest_sha256"]})')
    interpreter = source.get('interpreter') or {}
    here = [sys.version_info[0], sys.version_info[1], sys.version_info[2]]
    require(interpreter.get('implementation') == 'cpython' and list(interpreter.get('version') or [])[:2] == [3, 12], 'pins',
            f'records must be made with CPython 3.12; this one names {interpreter}')
    require(interpreter.get('version') == here and sys.implementation.name == 'cpython', 'pins',
            f'the record was made with CPython {interpreter.get("version")}; replay needs the same version '
            f'(this validator runs {sys.implementation.name} {here})')
    return variant


def run_json(command, cwd, check, timeout):
    try:
        done = subprocess.run(command, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=timeout, check=False)
    except subprocess.TimeoutExpired:
        raise Fail(check, f'timed out after {timeout} s')
    if done.returncode != 0:
        tail = (done.stderr.decode('utf-8', 'replace').strip().splitlines() or ['no message'])[-1]
        raise Fail(check, f'exit status {done.returncode}: {tail[:300]}')
    return done.stdout


def check_replay(run_path):
    out = run_json([sys.executable, '-B', str(ENV / 'bin' / 'headgasket-mcp'), 'replay', '--record', str(run_path)], ENV, 'replay', 3600)
    try:
        result = json.loads(out.decode('utf-8').strip().splitlines()[-1])
    except (ValueError, IndexError):
        raise Fail('replay', 'replay printed no result')
    require(result.get('ok') is True and result.get('exact') is True, 'replay', 'replay did not reproduce the record exactly')
    return result


def score(run_path):
    with tempfile.TemporaryDirectory() as tmp:
        target = Path(tmp) / 'score.json'
        run_json([sys.executable, '-B', 'hgj_scorer.py', 'score', str(run_path), '--checkpoint-revision', SCORER_REVISION,
                  '--json', str(target)], SCORER, 'scorer', 1800)
        report = json.loads(target.read_bytes())
    assessment = report['assessment']
    require(assessment['primary_comparison']['status'] == 'agreement', 'scorer',
            'the independent scorer disagrees with the environment score: '
            + json.dumps(assessment['primary_comparison'].get('disagreements'))[:300])
    disagreements = determined_disagreements(assessment['producer_comparison'])
    require(not disagreements, 'scorer',
            'the independent scorer disagrees on shared bolt, mistake or time fields: '
            + json.dumps(disagreements)[:300])
    return assessment


def determined_disagreements(comparison):
    """The shared-field disagreements that count: those on a value both scorers
    determine. The independent scorer reports some checklist items as unknown (null),
    for example on parts a run never touched; an unknown is not compared. Its mistake
    types include one the environment never produces (INDEPENDENT_ONLY_MISTAKE_TYPES);
    the mistake-type comparison leaves that type out and compares every other type.
    The primary checkpoints are compared separately and must always agree."""
    rows = []
    for row in comparison.get('disagreements') or []:
        independent = row.get('independent')
        if independent is None:
            continue
        if row.get('field') == 'mistakes/by_type' and isinstance(independent, dict):
            shared = {k: v for k, v in independent.items() if k not in INDEPENDENT_ONLY_MISTAKE_TYPES}
            if shared == row.get('producer'):
                continue
        rows.append(row)
    return rows


def result_fields(assessment, record, run_raw, nearest):
    """RESULT.md's rows. Points and checkpoints come from the independent scorer (the
    validator has checked that they equal the environment's). Technician seconds and
    mistake events are the environment's figures from the record, the same numbers the
    board shows: the independent scorer leaves some of them unknown (for example the
    penalty of a run that calls finish early) and has a mistake type the environment
    does not (missing_timing_verification), and the validator has checked that the two
    agree wherever both determine a value."""
    primary = assessment['primary_score']
    failed = [row['id'] for row in primary['checkpoints'] if not row['passed']]
    calls = assessment['tool_calls']
    human, mistakes = record['score']['human_time'], record['score']['mistakes']
    return [
        ('points', f'{primary["points_earned"]}/{primary["total_points"]}'),
        ('S_full', str(primary['S_full'])),
        ('S_partial', f'{primary["S_partial"]:.6f}'),
        ('failed checkpoints', ', '.join(failed) or 'none'),
        ('productive seconds', str(human['productive_seconds'])),
        ('penalty seconds', str(human['penalty_seconds'])),
        ('mistake events', str(mistakes['count'])),
        ('tool attempts', f'{calls["attempted"]} ({calls["refused"]} refused)'),
        ('finished', 'yes' if record['finished'] else 'no'),
        ('calls in common with a scripted record', describe_match(call_keys(record['actions']), nearest)),
        ('checkpoint revision', SCORER_REVISION),
        ('run.json sha256', sha(run_raw)),
    ]


def render_result(name, declaration, fields):
    lines = [f'# {name}', '',
             f'Submitted run. Model label `{declaration["model_label"]}` and client `{declaration["client"]}` are the '
             f'submitter\'s statement; variant {declaration["variant"]}; {declaration["date"]}.', '',
             'Scored by the repository scorer (`scorer/hgj_scorer.py`) and generated by '
             '`python3 tools/validate_submission.py --write-result`. Do not edit by hand.', '',
             '| Field | Value |', '|---|---|']
    lines += [f'| {key} | {value} |' for key, value in fields]
    lines += ['', 'Points and checkpoints are the same under the environment and the independent scorer. Technician '
              'seconds and mistake events are the environment\'s figures from the record, as on the board; the independent '
              'scorer agrees wherever it determines them. Technician seconds are analyst estimates, not measured labour. '
              'The calls in common are counted in order against the closest published scripted record (`runs/family/`, '
              '`runs/reference/`). ToolsEnabled verifies that the record replays exactly and scores the same under the '
              'independent scorer; it does not verify which model served the run.', '']
    return '\n'.join(lines)


def parse_result(raw):
    rows = {}
    for line in raw.decode('utf-8', 'replace').splitlines():
        cells = [cell.strip() for cell in line.strip().strip('|').split('|')]
        if line.strip().startswith('|') and len(cells) == 2:
            rows[cells[0]] = cells[1]
    return rows


def check_result(raw, fields):
    stated = parse_result(raw)
    for key, value in fields:
        require(key in stated, 'scorer', f'RESULT.md has no "{key}" row (regenerate it with --write-result)')
        require(stated[key] == value, 'scorer', f'RESULT.md says {key} = {stated[key]}; the validator finds {value}')


def validate(folder):
    files = check_files(folder)
    declaration = check_declaration(files['SUBMISSION.json'])
    check_secrets(files)
    record = check_chain(files)
    nearest, review = check_duplicate(folder, record, files)
    variant = check_pins(record, declaration)
    check_replay((folder / 'run.json').resolve())
    assessment = score((folder / 'run.json').resolve())
    fields = result_fields(assessment, record, files['run.json'], nearest)
    check_result(files['RESULT.md'], fields)
    generated = render_result(folder.name, declaration, fields).encode('utf-8')
    require(files['RESULT.md'].replace(b'\r\n', b'\n') == generated, 'scorer',
            'RESULT.md is not exactly the file --write-result generates (regenerate it; do not edit it)')
    values = dict(fields)
    return (f'{variant} {values["points"]} S_partial {values["S_partial"]}; '
            'files, declaration, secrets, chain, duplicate, pins, replay and scorer checks passed'
            + (f'; {review}' if review else ''))


def write_result(folder):
    folder = Path(folder)
    require(folder.is_dir() and not folder.is_symlink(), 'files', f'{folder} is not a folder')
    for name in ('SUBMISSION.json', 'run.json'):
        require((folder / name).is_file() and not (folder / name).is_symlink(), 'files', f'{name} is not a regular file')
    target = folder / 'RESULT.md'
    require(not target.is_symlink() and (not target.exists() or target.is_file()), 'files',
            'RESULT.md is a link or not a regular file; remove it and run --write-result again')
    declaration = check_declaration((folder / 'SUBMISSION.json').read_bytes())
    run_raw = (folder / 'run.json').read_bytes()
    record = json.loads(run_raw)
    check_attempt_count(record.get('actions') if isinstance(record, dict) else None)
    assessment = score((folder / 'run.json').resolve())
    nearest = closest(call_keys(record['actions']), scripted_records())
    text = render_result(folder.name, declaration, result_fields(assessment, record, run_raw, nearest))
    target.write_bytes(text.encode('utf-8'))
    return text


def main(argv=None):
    parser = argparse.ArgumentParser(description='Validate a submitted Head Gasket Bench run folder.')
    parser.add_argument('folder', help='runs/submitted/<name>')
    parser.add_argument('--write-result', action='store_true', help='score the record and write RESULT.md, then stop')
    args = parser.parse_args(argv)
    folder = Path(args.folder)
    try:
        if args.write_result:
            write_result(folder)
            print(f'WROTE {folder}/RESULT.md')
            return 0
        summary = validate(folder)
    except Fail as failure:
        print(f'FAIL {folder}: {failure.check}: {failure}')
        return 1
    except Exception as error:  # an unreadable input is a failed submission, not a crash
        print(f'FAIL {folder}: error: {type(error).__name__}: {error}')
        return 1
    print(f'PASS {folder}: {summary}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
